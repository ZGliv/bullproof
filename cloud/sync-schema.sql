CREATE TABLE IF NOT EXISTS sync_accounts(id TEXT PRIMARY KEY,recovery TEXT NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS sync_devices(token TEXT PRIMARY KEY,account TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sync_pairs(code TEXT PRIMARY KEY,account TEXT NOT NULL,expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS sync_ops(seq INTEGER PRIMARY KEY AUTOINCREMENT,account TEXT NOT NULL,id TEXT NOT NULL,key TEXT NOT NULL,value TEXT NOT NULL,UNIQUE(account,id));
CREATE INDEX IF NOT EXISTS sync_ops_account ON sync_ops(account,seq);
CREATE TABLE IF NOT EXISTS sync_rate(bucket TEXT PRIMARY KEY,n INTEGER NOT NULL);
